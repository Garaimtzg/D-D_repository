def _steps(*pairs):
    """_steps((1, 2), (4, 3)) -> lista de 20 valores que cambian en esos niveles."""
    out, val, i = [], None, 0
    for lvl in range(1, 21):
        while i < len(pairs) and pairs[i][0] <= lvl:
            val = pairs[i][1]
            i += 1
        out.append(val)
    return out


